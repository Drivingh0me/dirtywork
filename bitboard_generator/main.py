# bp is black pawn and wp is white pawn
pieces = ["wp", "bp", "n", "b", "r", "q", "k"]

def bitboardstr_to_int(bits):
    return int(bits, 2)

class Piece:
    def __init__(self, type: str):
        self.type = type

        match type:
            case "wp":
                self.mobility = np.array(w_pawn_mobility)
                self.mobility_fm = np.array(w_pawn_mobility_first_move)
            case "N":
                self.mobility = np.array(knight_mobility)
                self.mobility_fm = False
            case "B":
                self.mobility = np.array(bishop_mobility)
                self.mobility_fm = False
            case "R":
                self.mobility = np.array(rook_mobility)
                self.mobility_fm = False
            case "Q":
                self.mobility = np.array(queen_mobility)
                self.mobility_fm = False
            case "K":
                self.mobility = np.array(king_mobility)
                self.mobility_fm = False
            case "bp":
                self.mobility = np.array(b_pawn_mobility)
                self.mobility_fm = np.array(b_pawn_mobility_first_move)
            case "n":
                self.mobility = np.array(knight_mobility)
                self.mobility_fm = False
            case "b":
                self.mobility = np.array(bishop_mobility)
                self.mobility_fm = False
            case "r":
                self.mobility = np.array(rook_mobility)
                self.mobility_fm = False
            case "q":
                self.mobility = np.array(queen_mobility)
                self.mobility_fm = False
            case "k":
                self.mobility = np.array(king_mobility)
                self.mobility_fm = False
            case _:
                raise ValueError("Invalid piece.")

    def moves(self, position: int):
        # Return 8 x 8 matrix of moves on the board.
        if position >= 64:
            raise ValueError("position cannot be greater than 63.")

        # Piece location on main 8x8 board.
        piece_x = int(position % 8)
        piece_y = int(position / 8)

        # 0 indexed.
        row = 7 - piece_y
        col = 7 - piece_x

        # Add exception for pawns first move.

        out = self.mobility[row:row + 8, col:col + 8]

        return out

def array_to_int(arr):
    # Convert the board array to an int bitboard.
    str_num = ""
    str_arr = arr.astype(str)
    # print(np.array2string(str_arr, separator=''))
    for x in np.nditer(str_arr):
        str_num += x

    return bitboardstr_to_int(str_num)

# Make a took that will construct rust arrays as text files with bitboards.
def build_moveboard(piece):
    # Determine the moves the piece can make and build the board.
    out = np.zeros(64)

    for i in range(64):
        # loop over all positions and add int bitboard to out.
        out[i] = array_to_int(piece.moves(i))

    # Reverse order to make index 0 -> 63
    return np.flip(out)

def nparr_to_string(arr):
    out = ""
    for i in arr:
        out += f"{str(int(i))}, "

    return out

def make_bitboards():
    # Make and export all bitboards to a txt file.
    for p in pieces:
        with open(f"bitboards/{p}.txt", "w") as file:
            file.write(nparr_to_string(build_moveboard(Piece(p))))

